#!/usr/bin/env python3
"""After pin_module_code.py, pin the GameRegistry and Params creation hashes of both toolchains for Desk binding.

  python3 tools/pin_swarm_code.py          # write src/lib/SwarmCode.sol from out/ and out-launch/, rebuild both
  python3 tools/pin_swarm_code.py --check  # verify against the existing builds
"""
import argparse, json, re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from pin_module_code import build, creation_hash, HEX  # noqa: E402


def pins() -> list:
    return [creation_hash('out-launch', 'GameRegistry'), creation_hash('out', 'GameRegistry'),
            creation_hash('out-launch', 'Params'), creation_hash('out', 'Params')]


def source(h: list) -> str:
    return ('// SPDX-License-Identifier: MIT\npragma solidity 0.8.26;\n\n'
            '// Generated by tools/pin_module_code.py after module pins. Two toolchains, one source (see ModuleCode).\n'
            'library SwarmCode {\n'
            f'    bytes32 internal constant REGISTRY_LAUNCH = {h[0]};\n'
            f'    bytes32 internal constant REGISTRY_REPO = {h[1]};\n'
            f'    bytes32 internal constant PARAMS_LAUNCH = {h[2]};\n'
            f'    bytes32 internal constant PARAMS_REPO = {h[3]};\n\n'
            '    function isRegistry(bytes32 h) internal pure returns (bool) {\n'
            '        return h == REGISTRY_LAUNCH || h == REGISTRY_REPO;\n    }\n\n'
            '    function isParams(bytes32 h) internal pure returns (bool) {\n'
            '        return h == PARAMS_LAUNCH || h == PARAMS_REPO;\n    }\n}\n')


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--check', action='store_true')
    p.add_argument('--no-build', action='store_true')
    args = p.parse_args()
    path = Path('src/lib/SwarmCode.sol')
    h = pins()
    if args.check:
        assert HEX.findall(path.read_text()) == h, 'Stale SwarmDesk binding code hashes: regenerate pins'
        print('SwarmDesk registry/Params creation-code pins match both toolchains.')
        sys.exit(0)
    path.write_text(source(h))
    if not args.no_build:
        build(launch=True)
        build(launch=False)
    print(json.dumps({'registry': h[:2], 'params': h[2:]}, indent=2))
