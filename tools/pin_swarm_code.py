#!/usr/bin/env python3
"""After pin_module_code and forge build, pin exact registry/Params creation hashes for Desk binding."""
import json, subprocess, argparse, re
from pathlib import Path
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
def digest(name):
    a=json.loads(Path(f'out/{name}.sol/{name}.json').read_text())
    return subprocess.check_output(['cast','keccak',a['bytecode']['object']],text=True).strip()
hashes=[digest('GameRegistry'),digest('Params')]
path=Path('src/lib/SwarmCode.sol')
text='// SPDX-License-Identifier: MIT\npragma solidity 0.8.26;\n\n// Generated by tools/pin_swarm_code.py after module pins.\nlibrary SwarmCode {\n'
text+=f'    bytes32 internal constant REGISTRY = {hashes[0]};\n    bytes32 internal constant PARAMS = {hashes[1]};\n}}\n'
if args.check:
    assert re.findall('0x[0-9a-f]{64}',path.read_text())==hashes,'Stale SwarmDesk binding code hashes'
    print('SwarmDesk registry/Params creation-code pins match.')
else:path.write_text(text)
