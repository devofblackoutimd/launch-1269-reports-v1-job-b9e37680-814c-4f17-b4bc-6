#!/usr/bin/env python3
"""Pin canonical constructor bytecode hashes. Run forge build first; no network, no config edits."""
import argparse, json, subprocess
from pathlib import Path
NAMES=['RewardPool','FarmRewards','FarmCore','FarmItems','PackSale','StarterClaim','FeeRouter','GridOperator','Season','FarmEngine']
def source():
    lines=['// SPDX-License-Identifier: MIT','pragma solidity 0.8.26;','/// @notice Generated by tools/pin_module_code.py. Exact compiler-pinned creation code, no links.','library ModuleCode {','    function hash(uint256 role) internal pure returns (bytes32) {']
    for i,name in enumerate(NAMES):
        artifact=json.loads(Path(f'out/{name}.sol/{name}.json').read_text())
        code=artifact['bytecode']['object']
        digest=subprocess.check_output(['cast','keccak',code],text=True).strip()
        lines.append(f'        if (role == {i}) return {digest}; // {name}')
    lines += ['        return bytes32(0);','    }','}','']
    return '\n'.join(lines)
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    expected=source();path=Path('src/lib/ModuleCode.sol')
    if args.check:
        # forge fmt changes spacing only; compare hex digests.
        import re
        assert re.findall(r'0x[0-9a-f]{64}',path.read_text())==re.findall(r'0x[0-9a-f]{64}',expected),'Module creation bytecode changed: regenerate pins'
        print('All ten module creation-code pins match current artifacts.')
    else:path.write_text(expected)
