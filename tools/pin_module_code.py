#!/usr/bin/env python3
"""Pin the canonical creation-code hashes of the fourteen modules for BOTH toolchains (v3.9).

Two builds of the same source are pinned side by side:
  * launch: the IMD verifier settings (solc 0.8.26, optimizer 200, cancun, viaIR false, bytecode_hash none),
    produced here with environment overrides into `out-launch/` without touching foundry.toml;
  * repo: the repository's own foundry.toml (via_ir true, default ipfs metadata) into `out/`.
GameRegistry.register, SwarmDesk.bind and EndowmentEscrow.forward accept either pin. No network, no config edits.

  python3 tools/pin_module_code.py          # build both, write src/lib/ModuleCode.sol, rebuild both
  python3 tools/pin_module_code.py --check  # verify the pins against both existing builds (no rebuild)
  python3 tools/pin_module_code.py --no-build  # write pins from the existing out/ and out-launch/ artifacts
"""
import argparse, json, os, re, subprocess, sys
from pathlib import Path

NAMES = ['RewardPool', 'FarmRewards', 'FarmCore', 'FarmItems', 'PackSale', 'StarterClaim', 'FeeRouter',
         'GridOperator', 'Season', 'FarmEngine', 'Economy', 'Enhancement', 'Civic', 'Billboards']
LAUNCH_ENV = {'FOUNDRY_VIA_IR': 'false', 'FOUNDRY_BYTECODE_HASH': 'none', 'FOUNDRY_OUT': 'out-launch',
              'FOUNDRY_CACHE_PATH': 'cache-launch'}
HEX = re.compile(r'0x[0-9a-f]{64}')


def keccak(hex_code: str) -> str:
    return subprocess.check_output(['cast', 'keccak', hex_code], text=True).strip()


def build(launch: bool, skip_tests: bool = True) -> None:
    env = dict(os.environ)
    if launch:
        env.update(LAUNCH_ENV)
    cmd = ['forge', 'build']
    if skip_tests:
        cmd += ['--skip', 'test', '--skip', 'script']
    subprocess.check_call(cmd, env=env)


def creation_hash(out_dir: str, name: str) -> str:
    artifact = json.loads(Path(f'{out_dir}/{name}.sol/{name}.json').read_text())
    code = artifact['bytecode']['object']
    assert 'linkReferences' not in artifact['bytecode'] or not artifact['bytecode']['linkReferences'], name
    return keccak(code)


def runtime_size(out_dir: str, name: str) -> int:
    artifact = json.loads(Path(f'{out_dir}/{name}.sol/{name}.json').read_text())
    return (len(artifact['deployedBytecode']['object']) - 2) // 2


def module_pins() -> dict:
    return {'launch': [creation_hash('out-launch', n) for n in NAMES], 'repo': [creation_hash('out', n) for n in NAMES]}


def source(pins: dict) -> str:
    lines = ['// SPDX-License-Identifier: MIT', 'pragma solidity 0.8.26;', '',
             '/// @notice Generated by tools/pin_module_code.py. Exact creation-code pins of the fourteen modules, no links.',
             '/// @dev Two pins per role, both of this exact source: `launchHash` is the IMD verifier toolchain',
             '/// (solc 0.8.26, optimizer 200 runs, cancun, viaIR false, bytecode_hash none) and `repoHash` is the repository',
             '/// toolchain (foundry.toml: via_ir true, default metadata). Registration accepts either, so the game can be',
             '/// launched from the platform\'s build while the repository\'s own build keeps every local test exact.',
             'library ModuleCode {']
    for fn, key in (('launchHash', 'launch'), ('repoHash', 'repo')):
        lines.append(f'    function {fn}(uint256 role) internal pure returns (bytes32) {{')
        for i, name in enumerate(NAMES):
            lines.append(f'        if (role == {i}) return {pins[key][i]}; // {name}')
        lines += ['        return bytes32(0);', '    }', '']
    lines += ['    /// @notice True when `h` is one of the two pinned creation-code hashes of `role`.',
              '    function matches(uint256 role, bytes32 h) internal pure returns (bool) {',
              '        if (h == bytes32(0) || role >= 14) return false;',
              '        return h == launchHash(role) || h == repoHash(role);', '    }', '}', '']
    return '\n'.join(lines)


def check(pins: dict) -> None:
    text = Path('src/lib/ModuleCode.sol').read_text()
    found = HEX.findall(text)
    expected = pins['launch'] + pins['repo']
    assert found == expected, 'Module creation bytecode changed: regenerate pins with tools/pin_module_code.py'
    for name in NAMES:
        for out_dir in ('out-launch', 'out'):
            size = runtime_size(out_dir, name)
            assert size <= 24576, f'{name} runtime {size} exceeds EIP-170 in {out_dir}'
    print('All fourteen module creation-code pins match both toolchains; every runtime fits EIP-170.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--no-build', action='store_true')
    args = parser.parse_args()
    if args.check:
        check(module_pins())
        sys.exit(0)
    if not args.no_build:
        build(launch=True)
        build(launch=False)
    pins = module_pins()
    Path('src/lib/ModuleCode.sol').write_text(source(pins))
    if not args.no_build:
        # GameRegistry embeds ModuleCode: rebuild both so pin_swarm_code.py sees the final registry code.
        build(launch=True)
        build(launch=False)
    print(json.dumps(pins, indent=2))
